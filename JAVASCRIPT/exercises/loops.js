// Pyramid
let y = 0;
for (y; y < 10; y++) {
  console.log("*".repeat(y + 1));
}

// while loop
let w = 0;
while (w < 100) {
  console.log(w + 1);
  w++;
}

// do while loop
let z = 0;
do {
  console.log(z + 1);
  z++;
} while (z < 100);
